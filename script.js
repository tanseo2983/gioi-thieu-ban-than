"use strict";

// Mobile navigation stays usable with a keyboard and closes after a selection.
const menuToggle = document.querySelector(".menu-toggle");
const navigation = document.querySelector(".main-nav");

function closeMenu() {
  navigation.classList.remove("is-open");
  menuToggle.setAttribute("aria-expanded", "false");
  menuToggle.setAttribute("aria-label", "Mở menu điều hướng");
}

menuToggle.addEventListener("click", () => {
  const expanded = menuToggle.getAttribute("aria-expanded") !== "true";
  menuToggle.setAttribute("aria-expanded", String(expanded));
  menuToggle.setAttribute("aria-label", expanded ? "Đóng menu điều hướng" : "Mở menu điều hướng");
  navigation.classList.toggle("is-open", expanded);
});

navigation.addEventListener("click", (event) => {
  if (event.target.closest("a")) closeMenu();
});
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && menuToggle.getAttribute("aria-expanded") === "true") {
    closeMenu();
    menuToggle.focus();
  }
});
document.addEventListener("click", (event) => {
  if (!event.target.closest(".header-inner")) closeMenu();
});
window.matchMedia("(min-width: 761px)").addEventListener("change", closeMenu);

if ("IntersectionObserver" in window) {
  const sectionObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      navigation.querySelectorAll('a[href^="#"]').forEach((link) => {
        if (link.hash === `#${entry.target.id}`) link.setAttribute("aria-current", "location");
        else link.removeAttribute("aria-current");
      });
    });
  }, { rootMargin: "-15% 0px -60% 0px", threshold: 0 });
  document.querySelectorAll("main section[id]").forEach((section) => sectionObserver.observe(section));
}

const balloonLayer = document.getElementById("balloon-layer");
const greeting = document.getElementById("greeting");
const hint = document.getElementById("celebration-hint");
const replayButton = document.getElementById("replay-balloons");
const hideButton = document.getElementById("hide-celebration");
const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");
const balloonColors = ["#e7a4ae", "#98cfb9", "#9dbfdf", "#edcc7e", "#b5a6da", "#eca98a"];
let audioContext;
let hasOpenedGreeting = false;
let greetingTimer;
let greetingCleanupTimer;

const random = (min, max) => Math.random() * (max - min) + min;

// Created/resumed only inside a trusted click (also generated by touch or keyboard).
// A short, decaying noise burst plus a low oscillator produces a balloon "pop".
function playPop() {
  const AudioContextClass = window.AudioContext || window.webkitAudioContext;
  if (!AudioContextClass) return;
  try {
    if (!audioContext || audioContext.state === "closed") audioContext = new AudioContextClass();
    const context = audioContext;
    const play = () => {
      const now = context.currentTime;
      const duration = 0.14;
      const buffer = context.createBuffer(1, Math.ceil(context.sampleRate * duration), context.sampleRate);
      const samples = buffer.getChannelData(0);
      for (let index = 0; index < samples.length; index += 1) {
        samples[index] = (Math.random() * 2 - 1) * Math.pow(1 - index / samples.length, 3);
      }
      const noise = context.createBufferSource();
      noise.buffer = buffer;
      const filter = context.createBiquadFilter();
      filter.type = "lowpass";
      filter.frequency.setValueAtTime(3000, now);
      filter.frequency.exponentialRampToValueAtTime(450, now + duration);
      const noiseGain = context.createGain();
      noiseGain.gain.setValueAtTime(0.42, now);
      noiseGain.gain.exponentialRampToValueAtTime(0.001, now + duration);
      noise.connect(filter);
      filter.connect(noiseGain);
      noiseGain.connect(context.destination);

      const oscillator = context.createOscillator();
      const toneGain = context.createGain();
      oscillator.type = "sine";
      oscillator.frequency.setValueAtTime(180, now);
      oscillator.frequency.exponentialRampToValueAtTime(45, now + 0.09);
      toneGain.gain.setValueAtTime(0.3, now);
      toneGain.gain.exponentialRampToValueAtTime(0.001, now + 0.1);
      oscillator.connect(toneGain);
      toneGain.connect(context.destination);
      noise.onended = () => { noise.disconnect(); filter.disconnect(); noiseGain.disconnect(); };
      oscillator.onended = () => { oscillator.disconnect(); toneGain.disconnect(); };
      noise.start(now);
      noise.stop(now + duration);
      oscillator.start(now);
      oscillator.stop(now + 0.11);
    };
    if (context.state === "suspended") context.resume().then(play).catch(() => {});
    else play();
  } catch {
    // A device without audio support can still pop balloons and read the greeting.
  }
}

function showGreeting() {
  hasOpenedGreeting = true;
  greeting.classList.remove("is-leaving");
  greeting.innerHTML = '<div class="greeting-card"><p>Chúc mừng Ngày Nhà giáo Việt Nam 20/11</p><span>TRÂN TRỌNG GỬI ĐẾN THẦY CÔ</span></div>';
  clearTimeout(greetingTimer);
  clearTimeout(greetingCleanupTimer);
  greetingTimer = window.setTimeout(() => {
    greeting.classList.add("is-leaving");
    greetingCleanupTimer = window.setTimeout(() => {
      greeting.replaceChildren();
      greeting.classList.remove("is-leaving");
    }, 650);
  }, 5500);
}

function popBalloon(balloon) {
  if (balloon.classList.contains("is-popped")) return;
  // Freeze the current falling position so the burst happens exactly at the click.
  balloon.style.setProperty("--pop-transform", getComputedStyle(balloon).transform);
  balloon.classList.add("is-popped");
  balloon.disabled = true;
  playPop();
  if (!hasOpenedGreeting) showGreeting();
  // Preserve keyboard navigation after the focused balloon is removed.
  if (document.activeElement === balloon) replayButton.focus({ preventScroll: true });
  window.setTimeout(() => balloon.remove(), 250);
}

function releaseBalloons() {
  balloonLayer.replaceChildren();
  const width = document.documentElement.clientWidth;
  const count = reducedMotion.matches ? 7 : (width < 600 ? 13 : 19);
  const fragment = document.createDocumentFragment();
  for (let index = 0; index < count; index += 1) {
    const balloon = document.createElement("button");
    const size = random(width < 600 ? 33 : 38, width < 600 ? 44 : 53);
    const margin = 19;
    balloon.type = "button";
    balloon.className = "balloon";
    balloon.setAttribute("aria-label", `Bóng bay ${index + 1}: bấm để mở lời chúc 20/11`);
    balloon.style.setProperty("--size", `${size.toFixed(1)}px`);
    balloon.style.setProperty("--x", `${random(margin, Math.max(margin, width - size - margin)).toFixed(1)}px`);
    balloon.style.setProperty("--drift", `${random(-17, 17).toFixed(1)}px`);
    balloon.style.setProperty("--duration", `${random(14, 23).toFixed(2)}s`);
    balloon.style.setProperty("--delay", `${index === 0 ? 0 : random(0.15, 6).toFixed(2)}s`);
    balloon.style.setProperty("--rest-y", `${random(18, 78).toFixed(1)}vh`);
    balloon.style.setProperty("--balloon-color", balloonColors[index % balloonColors.length]);
    balloon.addEventListener("click", () => popBalloon(balloon));
    balloon.addEventListener("animationend", (event) => {
      if (event.animationName === "balloon-fall") balloon.remove();
    });
    // Freeze a balloon while keyboard users focus it, keeping it easy to activate.
    balloon.addEventListener("focus", () => { balloon.style.animationPlayState = "paused"; });
    balloon.addEventListener("blur", () => { balloon.style.animationPlayState = "running"; });
    fragment.appendChild(balloon);
  }
  balloonLayer.appendChild(fragment);
}

replayButton.addEventListener("click", () => {
  hasOpenedGreeting = false;
  releaseBalloons();
});
hideButton.addEventListener("click", () => {
  balloonLayer.replaceChildren();
  greeting.replaceChildren();
  clearTimeout(greetingTimer);
  clearTimeout(greetingCleanupTimer);
  hint.hidden = true;
});
reducedMotion.addEventListener("change", () => { if (!hint.hidden) releaseBalloons(); });
let resizeTimer;
window.addEventListener("resize", () => {
  clearTimeout(resizeTimer);
  resizeTimer = window.setTimeout(() => { if (!hint.hidden) releaseBalloons(); }, 250);
});

// A finite shower on load; replay is available without reloading the page.
if (document.readyState === "complete") releaseBalloons();
else window.addEventListener("load", releaseBalloons, { once: true });
